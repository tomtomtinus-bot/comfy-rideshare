// Shared i18n strings for all transactional email templates.
// Each template has its own key namespace; values are objects keyed by locale.
// Fallback chain: requested locale -> 'nl' -> first defined.

export type Locale = 'nl' | 'en' | 'de' | 'fr'

export function normalizeLocale(raw: unknown): Locale {
  const v = typeof raw === 'string' ? raw.toLowerCase().slice(0, 2) : ''
  if (v === 'en' || v === 'de' || v === 'fr') return v
  return 'nl'
}

type Dict = Record<string, string | ((v: Record<string, any>) => string)>
type LocalePack = Record<Locale, Dict>

// Helper to define a string per locale (with optional interpolation fn).
function pick(pack: LocalePack, locale: Locale, key: string, vars: Record<string, any> = {}): string {
  const v = pack[locale]?.[key] ?? pack.nl[key]
  if (typeof v === 'function') return v(vars)
  if (typeof v !== 'string') return ''
  return v.replace(/\{\{(\w+)\}\}/g, (_, k) => (vars[k] ?? '') as string)
}

